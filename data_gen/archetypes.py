@dataclass(frozen=True)
class Archetype:
    """Параметры поведения архетипа.

    Средний чек здесь НЕ задаётся — он получается сам: цены блюд из
    category_weights × items_per_order. Гурман дорогой не потому, что так
    написано, а потому что берёт по 3-5 позиций из вина и стейков.
    """

    code: str
    title: str
    # Вероятности выбора категории. Категории вне словаря архетип не заказывает
    # (кроме шума — см. NOISE_RATE в generate.py).
    category_weights: dict[str, float]
    # Сколько позиций в одном заказе: равномерно из [min, max].
    items_per_order: tuple[int, int]
    # Сколько визитов за период генерации: равномерно из [min, max].
    visits_range: tuple[int, int]
    # Доля визитов, приходящихся на будни (бизнес-ланч ходит почти только в будни).
    weekday_bias: float = 0.7
    loyalty_tiers: tuple[str, ...] = field(default=("bronze", "silver", "gold"))


